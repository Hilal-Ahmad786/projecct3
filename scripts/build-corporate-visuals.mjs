// Converts the reviewed corporate-website SVG illustrations
// (src/components/services/corporate-visuals/source/*.svg) into a typed data
// module the animated components render inline.
//
//   node scripts/build-corporate-visuals.mjs
//
// - `id` attributes become `data-part` so several visuals can share one page
//   without duplicate DOM ids (most files reuse ids like "browser-chrome").
// - Stroke-only "draw" paths (listed in DRAW_PATHS) get pathLength="1" so CSS
//   can animate stroke-dashoffset from 1 to 0.
// - Label slots (<rect id="slot-…">) are removed from the markup and exported
//   as percentage boxes; HTML labels are positioned over them.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('../src/components/services/corporate-visuals/', import.meta.url).pathname;
const sourceDir = join(root, 'source');

const DRAW_PATHS = {
  'glyph-cms': ['publish-check-path'],
  'glyph-form': ['success-check-path'],
  'glyph-seo': ['link-1', 'link-2', 'link-3'],
  'site-tree': ['link-1', 'link-2', 'link-3', 'link-4', 'link-5', 'link-6'],
  handover: ['done-check-1', 'done-check-2', 'done-check-3', 'done-check-4', 'done-check-5'],
};

const out = {};
for (const file of readdirSync(sourceDir).filter((f) => f.endsWith('.svg')).sort()) {
  const name = file.replace(/\.svg$/, '');
  let svg = readFileSync(join(sourceDir, file), 'utf8').replace(/<!--[\s\S]*?-->/g, '').trim();
  const viewBox = svg.match(/viewBox="([^"]+)"/)[1];
  const [, , vw, vh] = viewBox.split(/\s+/).map(Number);

  const slots = {};
  svg = svg.replace(/<rect id="(slot-[^"]+)" x="([\d.]+)" y="([\d.]+)" width="([\d.]+)" height="([\d.]+)"[^>]*\/>/g, (_, id, x, y, w, h) => {
    slots[id] = { x: +(x / vw * 100).toFixed(3), y: +(y / vh * 100).toFixed(3), w: +(w / vw * 100).toFixed(3), h: +(h / vh * 100).toFixed(3) };
    return '';
  });

  for (const id of DRAW_PATHS[name] ?? []) {
    svg = svg.replace(new RegExp(`id="${id}"`), `id="${id}" pathLength="1"`);
  }
  svg = svg.replace(/\sid="/g, ' data-part="');
  const inner = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/<g data-part="lang-slots"><\/g>/, '');

  out[name] = { viewBox, width: vw, height: vh, markup: inner, slots };
}

const banner = '// Generated by scripts/build-corporate-visuals.mjs — do not edit by hand.\n';
writeFileSync(
  join(root, 'svgData.ts'),
  `${banner}export type CorporateVisualSlot = { x: number; y: number; w: number; h: number };\n` +
  `export type CorporateVisual = { viewBox: string; width: number; height: number; markup: string; slots: Record<string, CorporateVisualSlot> };\n\n` +
  `export const corporateVisuals = ${JSON.stringify(out, null, 2)} as const satisfies Record<string, CorporateVisual>;\n\n` +
  `export type CorporateVisualName = keyof typeof corporateVisuals;\n`,
);
console.log(`Wrote ${Object.keys(out).length} visuals`);
