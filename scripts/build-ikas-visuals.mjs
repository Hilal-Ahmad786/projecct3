// Turns the Codex-delivered ikas SVGs (src/components/ikas/visuals/svg) into
// inline-able markup: ids become `iv-*` classes (several visuals share ids such
// as `tile`), stroke-draw paths get pathLength="1", and `slot-*` rects are
// removed and returned as percentage boxes for HTML overlays (ikas logo).
// Run: node scripts/build-ikas-visuals.mjs
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const dir = 'src/components/ikas/visuals/svg';
const manifest = JSON.parse(readFileSync(join(dir, 'manifest.json'), 'utf8'));
const drawPaths = Object.fromEntries(manifest.files.map((f) => [f.file, new Set(f.drawPaths ?? [])]));
const out = {};

for (const file of readdirSync(dir).filter((f) => f.endsWith('.svg')).sort()) {
  let svg = readFileSync(join(dir, file), 'utf8').replace(/<!--[\s\S]*?-->/g, '').trim();
  const [, , , vw, vh] = svg.match(/viewBox="(\S+) (\S+) (\S+) (\S+)"/).map(Number);
  const slots = {};
  svg = svg.replace(/<rect\b[^>]*\bid="(slot-[^"]+)"[^>]*\/>/g, (tag, id) => {
    const n = (a) => Number(tag.match(new RegExp(`\\b${a}="(-?[\\d.]+)"`))[1]);
    const pct = (v, d) => Math.round((v / d) * 10000) / 100;
    slots[id] = { left: pct(n('x'), vw), top: pct(n('y'), vh), width: pct(n('width'), vw), height: pct(n('height'), vh) };
    return '';
  });
  const draws = drawPaths[file] ?? new Set();
  svg = svg.replace(/<path\b([^>]*)\bid="([^"]+)"/g, (m, pre, id) => (draws.has(id) ? `<path${pre}id="${id}" pathLength="1"` : m));
  svg = svg.replace(/\bid="([^"]+)"/g, 'class="iv-$1"');
  svg = svg.replace('<svg ', '<svg aria-hidden="true" focusable="false" ');
  out[file.replace(/\.svg$/, '')] = { viewBox: [vw, vh], slots, markup: svg };
}

const header = '// Generated by scripts/build-ikas-visuals.mjs from ./svg — do not edit by hand.\n';
writeFileSync('src/components/ikas/visuals/generated.ts', `${header}export const IKAS_VISUALS = ${JSON.stringify(out, null, 1)} as const;\n\nexport type IkasVisualName = keyof typeof IKAS_VISUALS;\n`);
console.log(Object.keys(out).length, 'visuals');
